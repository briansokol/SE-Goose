namespace IngameScript
{
    /// <summary>Horizontal alignment of a positioned text element relative to its anchor X.</summary>
    public enum DrawAlign
    {
        /// <summary>Text grows rightward from the anchor X.</summary>
        Left,

        /// <summary>Text is centered on the anchor X.</summary>
        Center,

        /// <summary>Text ends at the anchor X.</summary>
        Right
    }
}
